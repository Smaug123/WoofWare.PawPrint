using System;

// Math.Log(double) is [Intrinsic] + InternalCall in CoreCLR: it has no IL body, and the JIT lowers
// it to a call into the platform C library's `log`. PawPrint implements it in-tree instead
// (DeterministicMath.log), so that a replay cannot depend on which libm the recording machine had.
//
// This file runs under both PawPrint and the real runtime and the two exit codes are compared, so
// it may only assert things *both* must agree on. `log` is not correctly rounded by mainstream
// libms, so nothing below pins a last bit that is not forced: the assertions are the special cases
// C99 Annex F fixes exactly, arguments whose true logarithm lies so close to a double that any
// implementation within an ulp of the truth rounds to it, and identities that hold of the real
// logarithm and so must hold of any faithful approximation to within a slack far wider than an ulp.
//
// The one place the standards leave open is the payload of a NaN, whether generated by the domain
// error at a negative argument or propagated from a NaN one: hosts differ on both the payload and
// the sign. So the NaN cases below check double.IsNaN and never the bits. The bit-exact
// specification of PawPrint's own answer lives in TestDeterministicMath.fs.
//
// Every failure code below is distinct and stays under 128. A process exit code is eight bits, so a
// code of 256 would reach the harness as 0 and a wrong answer would read as success; and codes from
// 128 up are indistinguishable from the 128+signo of a guest that died on a signal. That is why the
// loops report a bucket of their index rather than the index itself.
public static class MathLog
{
    const double Ln2 = 0.69314718055994530942;

    static int SpecialCases()
    {
        // C17 F.10.3.7: log(1) is +0, and the sign of that zero is specified.
        if (Math.Log(1.0) != 0.0) return 1;
        if (double.IsNegative(Math.Log(1.0))) return 2;

        // log(±0) is -infinity, a pole rather than a domain error: both zeros alike.
        if (!double.IsNegativeInfinity(Math.Log(0.0))) return 3;
        if (!double.IsNegativeInfinity(Math.Log(-0.0))) return 4;

        if (!double.IsPositiveInfinity(Math.Log(double.PositiveInfinity))) return 5;

        // Every argument below zero is a domain error, -infinity included.
        if (!double.IsNaN(Math.Log(-1.0))) return 6;
        if (!double.IsNaN(Math.Log(-double.Epsilon))) return 7;
        if (!double.IsNaN(Math.Log(double.MinValue))) return 8;
        if (!double.IsNaN(Math.Log(double.NegativeInfinity))) return 9;

        // NaN propagates. Which NaN is deliberately not asserted; see the file comment.
        if (!double.IsNaN(Math.Log(double.NaN))) return 10;

        return 0;
    }

    static int NextToOne()
    {
        // The arguments where cancellation would bite an implementation that computed
        // `e * ln 2 + ln m` with m in [1, 2): just below 1 it would subtract two numbers near
        // ln 2. Both answers below are forced for any implementation within three quarters of an
        // ulp of the truth.

        // ln(1 + 2^-52) = 2^-52 - 2^-105 + 2^-156/3 - ..., which lies within 2^-158 of the double
        // 2^-52 - 2^-105, the predecessor of 2^-52.
        double justAbove = Math.BitIncrement(1.0);
        double twoToMinus52 = 2.220446049250313e-16;
        if (Math.Log(justAbove) != Math.BitDecrement(twoToMinus52)) return 21;

        // ln(1 - 2^-53) = -2^-53 - 2^-107 - ..., a quarter of an ulp from -2^-53.
        double justBelow = Math.BitDecrement(1.0);
        double twoToMinus53 = 1.1102230246251565e-16;
        if (Math.Log(justBelow) != -twoToMinus53) return 22;

        // Further out the series is still dominated by its first term: ln(1 + u) is u to within
        // u^2/2, which these tolerances allow for with room to spare.
        double u = 1.0 / (1 << 30);
        if (Math.Abs(Math.Log(1.0 + u) - u) > u * u) return 23;
        if (Math.Abs(Math.Log(1.0 - u) + u) > u * u) return 24;

        return 0;
    }

    static int PowersOfTwo()
    {
        // ln(2^k) = k ln 2, across the whole exponent range including the subnormals. The
        // tolerance is a few ulps of the result.
        for (int k = -1074; k <= 1023; k++)
        {
            double x = Math.ScaleB(1.0, k);
            double expected = k * Ln2;
            double actual = Math.Log(x);

            if (Math.Abs(actual - expected) > 4e-16 * Math.Max(1.0, Math.Abs(expected)))
                return 30 + (((k % 8) + 8) % 8);
        }

        return 0;
    }

    static int ProductRule()
    {
        // ln(x * 2^k) = ln(x) + k ln 2. Scaling by a power of two is exact, so both sides really
        // are the same real number, and a mistake in how the exponent is split off from the
        // mantissa shows up here by a margin of order ln 2, not of order an ulp.
        double[] arguments =
        {
            1.5, 3.0, 0.1, 0.7, 1.4142135623730951, 0.70710678118654757, 10.0, 123.456,
            6.02214076e23, 1.602176634e-19,
        };

        int[] shifts = { -900, -100, -1, 1, 7, 100, 900 };

        for (int i = 0; i < arguments.Length; i++)
        {
            double x = arguments[i];

            for (int j = 0; j < shifts.Length; j++)
            {
                double scaled = Math.ScaleB(x, shifts[j]);
                double lhs = Math.Log(scaled);
                double rhs = Math.Log(x) + shifts[j] * Ln2;

                if (Math.Abs(lhs - rhs) > 1e-12) return 40 + (i % 8);
            }
        }

        return 0;
    }

    static int KnownValues()
    {
        // Values whose logarithm is known to far more digits than a double holds, checked to a
        // relative tolerance of a few ulps.
        (double x, double ln)[] table =
        {
            (2.0, 0.69314718055994530942),
            (10.0, 2.3025850929940456840),
            (0.5, -0.69314718055994530942),
            (3.0, 1.0986122886681096914),
            (Math.E, 1.0),
            (double.MaxValue, 709.78271289338399684),
            (double.Epsilon, -744.44007192138126231),
            (2.2250738585072014e-308, -708.39641853226410622),
        };

        for (int i = 0; i < table.Length; i++)
        {
            double actual = Math.Log(table[i].x);

            if (Math.Abs(actual - table[i].ln) > 4e-16 * Math.Abs(table[i].ln))
                return 50 + i;
        }

        return 0;
    }

    static int IsMonotone()
    {
        // A strictly increasing function, sampled far enough apart that a one-ulp disagreement
        // between implementations cannot reorder adjacent results. The array is in increasing
        // order, which this also checks.
        double[] increasing =
        {
            double.Epsilon, 1e-320, 1e-300, 1e-100, 1e-10, 0.1, 0.5, 0.9, 0.999999, 1.0,
            1.000001, 1.1, 2.0, 10.0, 1e10, 1e100, 1e300, double.MaxValue,
        };

        double previous = double.NegativeInfinity;

        for (int i = 0; i < increasing.Length; i++)
        {
            double r = Math.Log(increasing[i]);

            if (!(r > previous)) return 70 + (i % 8);

            previous = r;
        }

        return 0;
    }

    static int ArbitraryBase()
    {
        // Math.Log(a, newBase) has an ordinary IL body, which divides two calls to Math.Log(a).
        // It is here because it is how most guests reach the one-argument form.
        if (Math.Abs(Math.Log(8.0, 2.0) - 3.0) > 1e-15) return 81;
        if (Math.Abs(Math.Log(1000.0, 10.0) - 3.0) > 1e-15) return 82;
        if (Math.Abs(Math.Log(0.25, 2.0) + 2.0) > 1e-15) return 83;

        // The cases its body answers before dividing.
        if (!double.IsNaN(Math.Log(5.0, 1.0))) return 84;
        if (!double.IsNaN(Math.Log(5.0, 0.0))) return 85;
        if (!double.IsNaN(Math.Log(double.NaN, 2.0))) return 86;

        return 0;
    }

    public static int Main(string[] args)
    {
        int result;

        result = SpecialCases();
        if (result != 0) return result;

        result = NextToOne();
        if (result != 0) return result;

        result = PowersOfTwo();
        if (result != 0) return result;

        result = ProductRule();
        if (result != 0) return result;

        result = KnownValues();
        if (result != 0) return result;

        result = IsMonotone();
        if (result != 0) return result;

        result = ArbitraryBase();
        if (result != 0) return result;

        return 0;
    }
}
