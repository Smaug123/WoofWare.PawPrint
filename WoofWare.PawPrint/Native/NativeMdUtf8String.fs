    /// Decode a counted, *not* null-terminated UTF-8 buffer to UTF-16, exactly as CoreCLR's
    /// `StackSString lhs(SString::Utf8, szLhs, stringNumBytes)` does
    /// (`src/coreclr/vm/runtimehandles.cpp:51`). Malformed UTF-8 cannot arise from the two
    /// real callers -- one operand is a metadata `#Strings` name and the other is
    /// `Encoding.UTF8.GetBytes` of a managed string (`RuntimeType.CoreCLR.cs:353`) -- so
    /// reject it loudly rather than silently substituting replacement characters.
    let private decodeUtf8 (operation : string) (operandName : string) (bytes : byte array) : string =
        let encoding = UTF8Encoding (false, true)

        try
            encoding.GetString bytes
        with :? DecoderFallbackException as e ->
            failwith
                $"%s{operation}: %s{operandName} operand is not valid UTF-8 (%d{bytes.Length} bytes): %s{e.Message}"

