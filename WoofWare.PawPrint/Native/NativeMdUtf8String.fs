    let private simpleUpperTable : Map<char, char> =
        simpleUpperMappings
        |> Array.map (fun (lower, upper) -> char lower, char upper)
        |> Map.ofArray

    /// CoreCLR's `SIMPLE_UPCASE` / `MapChar(ch, LCMAP_UPPERCASE)` pair from
    /// `SString::CaseCompareHelper` (`src/coreclr/utilcode/sstring.cpp:133`, with the macros at
    /// `sstring.cpp:100`-`105`): code units <= 0x7F take the branch-free `a`-`z` fold, and
    /// everything else goes through the *invariant simple* uppercase mapping, which on Unix is
    /// `minipal_toupper_invariant` (`sstring.cpp:82`) -- see `simpleUpperMappings`.
    ///
    /// This is deliberately *not* full case folding, and it works on UTF-16 code units rather
    /// than scalars, so a surrogate pair is never folded as a unit: the table has no surrogate
    /// rows, so each half maps to itself.
    ///
    /// Public only so that `TestNativeMdUtf8String.fs` can assert the embedded table's
    /// invariants; the comparison itself is the module's real contract.
    let simpleUpperInvariant (c : char) : char =
        if c <= '\u007F' then
            if c >= 'a' && c <= 'z' then
                char (int c - int 'a' + int 'A')
            else
                c
        else
            match Map.tryFind c simpleUpperTable with
            | Some upper -> upper
            | None -> c

    /// The comparison behind `MdUtf8String_EqualsCaseInsensitive`
    /// (`src/coreclr/vm/runtimehandles.cpp:35`), which builds a `StackSString` from each
    /// counted UTF-8 buffer and calls `SString::EqualsCaseInsensitive`
    /// (`src/coreclr/utilcode/sstring.cpp:1463`).
    ///
    /// `SString::EqualsCaseInsensitive` normalises both operands to a common fixed-width
    /// representation first (`GetCompatibleString`, `sstring.cpp:2019`): pure-ASCII operands
    /// stay 8-bit and take `CaseCompareHelperA`, anything else is transcoded to UTF-16 and
    /// takes `CaseCompareHelper`. Both helpers apply the same `a`-`z` fold to ASCII, and the
    /// ASCII path is only reachable when neither operand has a byte >= 0x80, so the two paths
    /// agree and we can implement the single UTF-16 rule:
    ///
    ///   - decode both operands to UTF-16;
    ///   - unequal UTF-16 lengths compare unequal (`count != source.GetRawCount()`, which is a
    ///     *character* count, so equal byte counts do not imply equal lengths here);
    ///   - otherwise compare code unit by code unit under `simpleUpperInvariant`.
    ///
    /// The semantics were cross-checked against the real runtime by differential test
    /// (`sourcesPure/MdUtf8StringEqualsCaseInsensitive.cs`): U+00E9/U+00C9 and U+03C2/U+03C3
    /// compare equal, so the fold really is Unicode-aware rather than ASCII-only, while
    /// non-letter ASCII such as `<` and `\` does not fold.
    ///
    /// CoreCLR's callers only reach this comparison when the two buffers have equal byte
    /// lengths (`MdUtf8String.EqualsCaseInsensitive`, `RuntimeType.CoreCLR.cs:4371`), but the
    /// QCall itself is length-agnostic beyond that, and so is this.
    let equalsCaseInsensitive (operation : string) (lhs : byte array) (rhs : byte array) : bool =
        let lhs = decodeUtf8 operation "lhs" lhs
        let rhs = decodeUtf8 operation "rhs" rhs

        lhs.Length = rhs.Length
        && Seq.forall2 (fun (a : char) (b : char) -> a = b || simpleUpperInvariant a = simpleUpperInvariant b) lhs rhs

    let private byteCountOfArgument (operation : string) (arg : CliType) : int =
        match CliType.unwrapPrimitiveLikeDeep arg with
        | CliType.Numeric (CliNumericType.Int32 count) -> count
        | other -> failwith $"%s{operation}: expected Int32 byte count, got %O{other}"

    let tryExecuteQCall (entryPoint : string) (ctx : NativeCallContext) : NativeHandlerResult option =
        let state = ctx.State
        let instruction = ctx.Instruction

        match
            entryPoint,
            ctx.TargetAssembly.Name.Name,
            ctx.TargetType.Namespace,
            ctx.TargetType.Name,
            instruction.ExecutingMethod.Signature.ParameterTypes,
            instruction.ExecutingMethod.Signature.ReturnType
        with
        | "MdUtf8String_EqualsCaseInsensitive",
          "System.Private.CoreLib",
          "System",
          "MdUtf8String",
          [ ConcretePointer (ConcreteVoid state.ConcreteTypes)
            ConcretePointer (ConcreteVoid state.ConcreteTypes)
            ConcretePrimitive state.ConcreteTypes PrimitiveType.Int32 ],
          // CoreLib declares `[return: MarshalAs(UnmanagedType.Bool)] bool`; the QCall
          // PInvoke stub presents this to us as a 4-byte Int32 (Win32 BOOL).
          MethodReturnType.Returns (ConcretePrimitive state.ConcreteTypes PrimitiveType.Int32) ->
            let operation = "MdUtf8String_EqualsCaseInsensitive"

            if instruction.Arguments.Length <> 3 then
                failwith
                    $"%s{operation}: expected three native arguments after matching signature, got %d{instruction.Arguments.Length}"

            let lhsPtr =
                NativeCall.managedPointerOfPointerArgument operation "szLhs" instruction.Arguments.[0]

            let rhsPtr =
                NativeCall.managedPointerOfPointerArgument operation "szRhs" instruction.Arguments.[1]

            let byteCount = byteCountOfArgument operation instruction.Arguments.[2]

            // CoreCLR asserts both pointers are non-null (`CheckPointer`,
            // runtimehandles.cpp:46) and the managed wrapper never calls in with a zero
            // length, so `readCountedUtf8Bytes` faulting on a null pointer here is the
            // right behaviour rather than something to paper over.
            let lhs =
                NativeCall.readCountedUtf8Bytes operation ctx.BaseClassTypes state lhsPtr byteCount

            let rhs =
                NativeCall.readCountedUtf8Bytes operation ctx.BaseClassTypes state rhsPtr byteCount

            let result = if equalsCaseInsensitive operation lhs rhs then 1 else 0

            state
            |> IlMachineState.pushToEvalStack (CliType.Numeric (CliNumericType.Int32 result)) ctx.Thread
            |> NativeHandlerResult.completed
            |> Some
        | _ -> None
